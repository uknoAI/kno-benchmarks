package summary

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// LatestSchemaVersion versions results/latest.json, the site-consumable
// document. It is this repository's own schema and never a proto concern.
const LatestSchemaVersion = 1

// Latest is results/latest.json.
type Latest struct {
	SchemaVersion int    `json:"schema_version"`
	Status        string `json:"status"`
	StatusDetail  string `json:"status_detail"`
	// DerivedFrom is deterministic — a count and the newest observation, not
	// a generation timestamp. A wall-clock stamp would make the
	// regenerate-and-diff check fail on every run and train reviewers to
	// ignore it.
	DerivedFrom struct {
		ResultFiles    int      `json:"result_files"`
		NewestResultAt string   `json:"newest_result_at"`
		MatrixSHA256   []string `json:"matrix_sha256"`
	} `json:"derived_from"`
	// CitableFigures is empty for as long as the runner gate in RUNNER.md is
	// open. A consumer that finds nothing here is being told the truth.
	CitableFigures []Figure `json:"citable_figures"`
}

// LatestJSON renders results/latest.json.
func (r *Report) LatestJSON() ([]byte, error) {
	l := Latest{SchemaVersion: LatestSchemaVersion, CitableFigures: []Figure{}}
	for _, f := range r.Figures {
		if f.Citable {
			l.CitableFigures = append(l.CitableFigures, f)
		}
	}
	l.DerivedFrom.ResultFiles = len(r.Runs)
	seen := map[string]bool{}
	newest := ""
	for _, run := range r.Runs {
		if !seen[run.MatrixSHA256] && run.MatrixSHA256 != "" {
			seen[run.MatrixSHA256] = true
			l.DerivedFrom.MatrixSHA256 = append(l.DerivedFrom.MatrixSHA256, run.MatrixSHA256)
		}
		if ts := run.StartedAt.UTC().Format("2006-01-02T15:04:05Z"); ts > newest {
			newest = ts
		}
	}
	sort.Strings(l.DerivedFrom.MatrixSHA256)
	l.DerivedFrom.NewestResultAt = newest

	if len(l.CitableFigures) == 0 {
		l.Status = "no-citable-figures"
		l.StatusDetail = "This repository has published no citable measurement of kno. " +
			"The hosted-runner bootstrap is measuring the runner's own variance; until that gate closes, " +
			"every figure here describes the machine, not the software. See METHODOLOGY.md and RUNNER.md."
	} else {
		l.Status = "ok"
		l.StatusDetail = "Every figure carries n, median, p25, p75 and CV, and a claim string that must be rendered adjacent to the number."
	}

	blob, err := json.MarshalIndent(l, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode latest.json: %w", err)
	}
	return append(blob, '\n'), nil
}

// Markdown renders SUMMARY.md. It is generated, never hand-edited: CI
// regenerates and diffs.
func (r *Report) Markdown() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `go run ./cmd/knobench summarize`. Do not edit: CI regenerates this file and fails on a diff. -->\n\n")
	b.WriteString("# SUMMARY\n\n")

	citable := 0
	for _, f := range r.Figures {
		if f.Citable {
			citable++
		}
	}
	fmt.Fprintf(&b, "**Citable figures about kno: %d.**\n\n", citable)
	if citable == 0 {
		b.WriteString("There are none, and that is the honest state of this repository today. " +
			"No host that produced the data below is a committed measurement machine — see `RUNNER.md` — so every " +
			"figure here describes the machine it ran on at least as much as it describes kno. The runs table names " +
			"each one. They exist to answer a single question, *how much does the measuring host vary?*, because that " +
			"answer — and not a third party's blog post — is what the hardware decision in `RUNNER.md` must be made " +
			"on.\n\n")
	}

	b.WriteString("## Exclusion rules and whether they were honoured\n\n")
	if len(r.Rules) == 0 {
		b.WriteString("No exclusion rules were found in `METHODOLOGY.md`.\n\n")
	} else {
		b.WriteString("| Rule | In git history | Observations it could not be applied to |\n|---|---|---|\n")
		ids := make([]string, 0, len(r.Rules))
		for id := range r.Rules {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		for _, id := range ids {
			rule := r.Rules[id]
			when := "no"
			if rule.Committed {
				when = "yes"
			}
			fmt.Fprintf(&b, "| %s | %s | %d |\n", id, when, r.RefusedExclusions[id])
		}
		// The exact commit timestamp is deliberately not rendered here. It is
		// what the summarizer compares against, but printing it into a
		// diff-checked artifact would make that artifact change on every
		// rebase, amend and squash-merge — and a generated file that fails its
		// own check for reasons nobody caused is a check people learn to
		// ignore. `git log --format=%aI -S<ID> -- METHODOLOGY.md` is the
		// authoritative answer and does not need a copy here.
		b.WriteString("\nAn exclusion whose rule was committed **after** an observation is refused, and the observation " +
			"is kept. That widens the spread rather than narrowing it, which is the only direction this check is " +
			"allowed to fail in. The commit that introduced each rule is in " +
			"`git log --format=%aI -S<ID> -- METHODOLOGY.md`.\n\n")
	}

	b.WriteString("## Runs\n\n")
	b.WriteString("| Result file | Track | kno | Started | Runner | Machine | Reps | Digest verified | Partial |\n|---|---|---|---|---|---|---|---|---|\n")
	for _, run := range r.Runs {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | `%s` | %d | %v | %v |\n",
			run.Path, run.Track, orUnknown(run.KnoVersion), run.StartedAt.UTC().Format("2006-01-02T15:04Z"),
			orUnknown(run.Runner), short(run.MachineID), run.Repetitions, run.ChecksumOK, run.Partial)
	}
	b.WriteString("\n")

	r.writeFigures(&b, ScopeWithinRun, "## Within-run spread (one machine repeating itself)",
		"This is the variance of one host measuring the same configuration `n` times in a row. "+
			"It is the smallest spread this setup can produce.")
	r.writeFigures(&b, ScopeBetweenRun, "## Between-run spread (across runs)",
		"Each observation here is one run's median. Where the runs landed on different hosts — which is every run "+
			"on a GitHub-hosted runner — this spread is the fleet's heterogeneity rather than the software's. "+
			"**This is the number the hardware decision turns on.**")

	b.WriteString("## What none of this claims\n\n")
	b.WriteString("- Nothing above is a claim about kno's performance. See `CITATION.md`.\n")
	b.WriteString("- Every figure is `fake:` — a local, deterministic, free agent. It excludes provider latency, " +
		"which dominates every real run.\n")
	b.WriteString("- No figure is compared to any other tool, ever.\n")
	return b.String()
}

func (r *Report) writeFigures(b *strings.Builder, scope, heading, blurb string) {
	fmt.Fprintf(b, "%s\n\n%s\n\n", heading, blurb)
	b.WriteString("| Config | Stage | Metric | n | median | p25 | p75 | min | max | CV | Flags |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
	rows := 0
	// Combinations that produced no figure are not dropped — they are listed
	// below the table, grouped by the reason. Rendering sixty rows of dashes
	// buries the ones that carry a measurement; deleting them would hide an
	// absence. Naming every one under its reason does neither.
	noFigure := map[string][]string{}
	for _, f := range r.Figures {
		if f.Scope != scope {
			continue
		}
		if !f.HasStats {
			reason := strings.Join(f.Flags, ", ")
			noFigure[reason] = append(noFigure[reason], fmt.Sprintf("`%s`/%s/%s", f.ConfigID, f.Stage, f.Metric))
			continue
		}
		rows++
		fmt.Fprintf(b, "| `%s` | %s | %s | %d | %s | %s | %s | %s | %s | %s | %s |\n",
			f.ConfigID, f.Stage, f.Metric, f.Stats.N,
			num(f.Stats.Median, f.Unit), num(f.Stats.P25, f.Unit), num(f.Stats.P75, f.Unit),
			num(f.Stats.Min, f.Unit), num(f.Stats.Max, f.Unit), cvString(f.Stats),
			strings.Join(f.Flags, ", "))
	}
	if rows == 0 {
		b.WriteString("| — | — | — | — | — | — | — | — | — | — | no figure at this scope |\n")
	}
	b.WriteString("\n")
	if len(noFigure) > 0 {
		reasons := make([]string, 0, len(noFigure))
		for k := range noFigure {
			reasons = append(reasons, k)
		}
		sort.Strings(reasons)
		b.WriteString("No figure was produced for these, and the reason is recorded rather than the row deleted:\n\n")
		for _, reason := range reasons {
			ids := noFigure[reason]
			sort.Strings(ids)
			fmt.Fprintf(b, "- **%s** — %d combination(s): %s\n", reason, len(ids), strings.Join(ids, ", "))
		}
		b.WriteString("\n")
	}
}

func short(s string) string {
	if len(s) > 12 {
		return s[:12]
	}
	if s == "" {
		return "unknown"
	}
	return s
}
